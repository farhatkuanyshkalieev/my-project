"""Trace the Atlantis Dent logo from a screenshot of their Instagram avatar into src/logo.generated.ts.

The avatar is black-on-white; the traced shapes are split into the two tooth strokes,
the wordmark and the sparkle so the intro can animate them separately.

usage: python3 -I scripts/trace_logo.py avatar.jpg   (needs: pip install potracer pillow numpy)
"""
import json
import sys

import numpy as np
import potrace
from PIL import Image

UP = 8  # trace at 8x so the curves come out smooth
CX, CY, R = 295, 555, 188  # avatar circle in the 591x1280 screenshot
BOX = (130, 390, 460, 720)

img = Image.open(sys.argv[1]).convert("L").crop(BOX)
w, h = img.size
a = np.asarray(img.resize((w * UP, h * UP), Image.LANCZOS)).astype(float)
yy, xx = np.mgrid[0 : h * UP, 0 : w * UP] / UP
a[(xx + BOX[0] - CX) ** 2 + (yy + BOX[1] - CY) ** 2 > R * R] = 255  # blank out the dark page around the avatar

p = lambda pt: f"{pt.x / UP:.1f} {pt.y / UP:.1f}"
parts = []
for curve in potrace.Bitmap(a < 128).trace(turdsize=40, alphamax=1.0, opttolerance=0.3):
    d = [f"M{p(curve.start_point)}"]
    pts = [curve.start_point]
    for seg in curve.segments:
        if seg.is_corner:
            d.append(f"L{p(seg.c)}L{p(seg.end_point)}")
        else:
            d.append(f"C{p(seg.c1)} {p(seg.c2)} {p(seg.end_point)}")
        pts.append(seg.end_point)
    xs = [q.x / UP for q in pts]
    ys = [q.y / UP for q in pts]
    parts.append(((min(xs), min(ys), max(xs), max(ys)), "".join(d) + "Z"))

parts = [(bb, d) for bb, d in parts if bb[2] - bb[0] < w - 2]  # drop the crop's own border
tooth = sorted([x for x in parts if x[0][3] - x[0][1] > 200], key=lambda x: x[0][0])
sparkle = [x for x in parts if x[0][3] < 140 and x[0][3] - x[0][1] > 40]
text = [x for x in parts if x not in tooth and x not in sparkle]
assert len(tooth) == 2 and len(sparkle) == 1, (len(tooth), len(sparkle))

out = {
    "LOGO_TOOTH_LEFT": tooth[0][1],
    "LOGO_TOOTH_RIGHT": tooth[1][1],
    "LOGO_TEXT": "".join(d for _, d in text),
    "LOGO_SPARKLE": sparkle[0][1],
}
with open("src/logo.generated.ts", "w") as f:
    f.write("// Generated by scripts/trace_logo.py from the clinic's avatar. Coordinates are in a 330x330 box.\n")
    for k, v in out.items():
        f.write(f"export const {k} = {json.dumps(v)};\n")
print({k: len(v) for k, v in out.items()}, "sparkle bb", [round(v) for v in sparkle[0][0]])
