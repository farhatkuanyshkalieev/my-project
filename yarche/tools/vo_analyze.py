"""Build src/data/vo.ts: per-line duration + 60 fps mouth envelope.

Uses real audio from audio_src/vo/<ID>.mp3 when present (RMS envelope, trimmed
of leading/trailing silence); otherwise synthesises a syllable envelope from
the text so the animation can be blocked before the voice files arrive.
"""
import json, os, re, subprocess, sys
import numpy as np

FPS = 60
SR = 22050
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LINES = [
    ("L1", "L", "Это что… я?! Ты ненормальный!", 2.7),
    ("M1", "M", "Ненормально талантливый. Привыкай.", 2.4),
    ("L2", "L", "Нарисуешь меня ещё раз?", 1.7),
    ("M2", "M", "Хоть каждый день.", 1.5),
    ("M3", "M", "Лиз! Мою картину взяли на выставку!", 2.4),
    ("L3", "L", "Круто… А деньги за это будут?", 2.6),
    ("M4", "M", "Ну… это же опыт.", 1.7),
    ("L4", "L", "Я скинула тебе вакансию. Нормальная работа. Нормальные деньги.", 3.6),
    ("M5", "M", "А картины?", 1.0),
    ("L5", "L", "Марк, тебе двадцать семь. Хватит играть в художника.", 3.4),
    ("LP", "L", "Купи хлеба по дороге, ладно?", 1.9),
    ("M6", "M", "Да. Куплю.", 1.4),
    ("L6", "L", "Помнишь… ты рисовал меня на стаканчиках?", 2.8),
    ("M7", "M", "Угу.", 0.6),
    ("L7", "L", "Нарисуй меня… ещё раз.", 2.2),
    ("M8", "M", "Я уже не помню… как.", 2.3),
]
VOWELS = set("аеёиоуыэюяАЕЁИОУЫЭЮЯ")


def load(path):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-ac", "1", "-ar", str(SR), "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, dtype=np.float32)


def env_from_audio(x):
    hop = SR // FPS
    n = len(x) // hop
    rms = np.array([np.sqrt(np.mean(x[i * hop:(i + 1) * hop] ** 2) + 1e-12) for i in range(n)])
    db = 20 * np.log10(rms + 1e-9)
    on = np.where(db > -42)[0]
    if len(on) == 0:
        return [], 0, 0
    a, b = max(0, on[0] - 2), min(n, on[-1] + 4)
    seg = db[a:b]
    e = np.clip((seg + 45) / 30, 0, 1) ** 1.3
    # attack/release smoothing
    out, v = [], 0.0
    for s in e:
        v = v + (s - v) * (0.65 if s > v else 0.35)
        out.append(round(float(v), 3))
    return out, a / FPS, b / FPS


def env_synth(text, dur):
    n = int(dur * FPS)
    vow = [i for i, ch in enumerate(text) if ch in VOWELS]
    env = np.zeros(n)
    if not vow:
        return env.tolist()
    for k, ci in enumerate(vow):
        c = (ci + 0.5) / len(text) * n
        w = n / len(vow) * 0.55
        t = np.arange(n)
        env += np.exp(-0.5 * ((t - c) / (w * 0.5)) ** 2) * (0.7 + 0.3 * ((k * 7) % 3) / 2)
    # pauses at punctuation
    for m in re.finditer(r"[….,?!]", text):
        c = int((m.start() + 0.5) / len(text) * n)
        env[max(0, c - 3):c + 6] *= 0.15
    return np.clip(env, 0, 1).round(3).tolist()


def main():
    data = {}
    for lid, who, text, est in LINES:
        path = os.path.join(ROOT, "audio_src", "vo", f"{lid}.mp3")
        if os.path.exists(path):
            x = load(path)
            env, t0, t1 = env_from_audio(x)
            data[lid] = {"who": who, "text": text, "dur": round(len(env) / FPS, 3), "trim": [round(t0, 3), round(t1, 3)], "env": env, "real": True}
        else:
            env = env_synth(text, est)
            data[lid] = {"who": who, "text": text, "dur": est, "trim": [0, est], "env": env, "real": False}
    out = os.path.join(ROOT, "src", "data", "vo.ts")
    with open(out, "w") as fh:
        fh.write("// Generated by tools/vo_analyze.py — do not edit by hand.\n")
        fh.write("export type VoLine = {who: 'L' | 'M'; text: string; dur: number; trim: [number, number]; env: number[]; real: boolean};\n")
        fh.write("export const VO: Record<string, VoLine> = " + json.dumps(data, ensure_ascii=False) + ";\n")
    for k, v in data.items():
        print(k, v["dur"], "real" if v["real"] else "synth")


if __name__ == "__main__":
    main()
